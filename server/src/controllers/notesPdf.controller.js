import PDFDocument from 'pdfkit';
import { getNotes } from '../services/notes.service.js';
import { reportServerError } from '../middleware/sentry.js';

/**
 * GET /api/notes/:videoId/pdf
 * Streams a clean, print-friendly PDF of the stored study notes.
 * Works with both light and dark contexts — PDF itself is always light-on-white.
 */
export async function handleGetNotesPdf(req, res) {
    const { videoId } = req.params;
    if (!videoId) {
        return res.status(400).json({ error: 'videoId is required' });
    }

    try {
        const notes = await getNotes(videoId);
        if (!notes || !notes.sections || notes.sections.length === 0) {
            return res.status(404).json({ error: 'Notes not found or still generating' });
        }

        // ── Create PDF document ─────────────────────────────────────────────
        // bufferPages:true is REQUIRED so switchToPage() works in the footer
        // loop — without it pdfkit flushes pages immediately and the footer
        // text is silently dropped / written on the wrong page.
        const doc = new PDFDocument({
            size: 'A4',
            margins: { top: 56, bottom: 56, left: 60, right: 60 },
            bufferPages: true,
            info: {
                Title: `Study Notes — ${videoId}`,
                Author: 'VectorOne AI',
                Subject: 'AI-generated lecture study notes',
            },
        });

        // Stream directly to response
        res.setHeader('Content-Type', 'application/pdf');
        res.setHeader(
            'Content-Disposition',
            `attachment; filename="notes-${videoId}.pdf"`
        );
        doc.pipe(res);

        // ── Colour palette (clean, always-light for print) ──────────────────
        const C = {
            primary:  '#4F46E5', // indigo-600
            accent:   '#E11D48', // rose-600
            heading:  '#1E1B4B', // dark navy for section titles
            body:     '#1F2937', // near-black body text
            muted:    '#6B7280', // grey metadata
            keyBg:    '#EEF2FF', // indigo-50
            formulaBg:'#FFF1F2', // rose-50
            rule:     '#E5E7EB', // light separator
        };

        // ── Header ──────────────────────────────────────────────────────────
        doc
            .rect(0, 0, doc.page.width, 48)
            .fill(C.primary);

        doc
            .fillColor('#FFFFFF')
            .fontSize(15)
            .font('Helvetica-Bold')
            .text('VectorOne AI', 60, 15, { continued: true })
            .fillColor('rgba(255,255,255,0.7)')
            .font('Helvetica')
            .fontSize(10)
            .text('  ·  Study Notes', { continued: true })
            .fillColor('rgba(255,255,255,0.5)')
            .fontSize(9)
            .text(`  ·  ${new Date().toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' })}`, { align: 'left' });

        doc.moveDown(2.5);

        // ── Document title ───────────────────────────────────────────────────
        doc
            .fillColor(C.heading)
            .fontSize(20)
            .font('Helvetica-Bold')
            .text('Lecture Study Notes', { align: 'left' });

        doc
            .fillColor(C.muted)
            .fontSize(9)
            .font('Helvetica')
            .text(`Generated by VectorOne AI  ·  Video ID: ${videoId}`, { align: 'left' });

        doc.moveDown(0.8);

        // horizontal rule
        doc
            .moveTo(60, doc.y)
            .lineTo(doc.page.width - 60, doc.y)
            .strokeColor(C.rule)
            .lineWidth(1)
            .stroke();

        doc.moveDown(1);

        // ── Sections ─────────────────────────────────────────────────────────
        notes.sections.forEach((section, idx) => {
            // Section heading with coloured left bar
            const sY = doc.y;
            doc
                .rect(60, sY, 4, 18)
                .fill(C.primary);

            doc
                .fillColor(C.heading)
                .fontSize(13)
                .font('Helvetica-Bold')
                .text(section.title || `Section ${idx + 1}`, 72, sY, { lineGap: 2 });

            doc.moveDown(0.4);

            // Main content
            if (section.content && section.content.trim()) {
                doc
                    .fillColor(C.body)
                    .fontSize(10)
                    .font('Helvetica')
                    .text(section.content.trim(), {
                        indent: 12,
                        align: 'left',
                        lineGap: 3,
                    });
                doc.moveDown(0.5);
            }

            // Key Concepts box
            if (section.keyConcepts && section.keyConcepts.length > 0) {
                const boxY = doc.y;
                const lineHeight = 14;
                const boxPad = 10;
                const boxHeight = boxPad * 2 + lineHeight + section.keyConcepts.length * lineHeight + 4;

                // Check page break
                if (boxY + boxHeight > doc.page.height - 80) {
                    doc.addPage();
                }

                doc
                    .rect(60, doc.y, doc.page.width - 120, boxHeight)
                    .fill(C.keyBg);

                const innerY = doc.y + boxPad;
                doc
                    .fillColor(C.primary)
                    .fontSize(8)
                    .font('Helvetica-Bold')
                    .text('KEY CONCEPTS', 72, innerY, { characterSpacing: 0.8 });

                section.keyConcepts.forEach((concept, i) => {
                    doc
                        .fillColor(C.body)
                        .fontSize(10)
                        .font('Helvetica')
                        .text(`• ${concept}`, 72, innerY + lineHeight + i * lineHeight, { lineGap: 2 });
                });

                doc.y = doc.y + boxHeight + 4;
                doc.moveDown(0.3);
            }

            // Formulas box
            if (section.formulas && section.formulas.length > 0) {
                const boxY = doc.y;
                const lineHeight = 14;
                const boxPad = 10;
                const boxHeight = boxPad * 2 + lineHeight + section.formulas.length * lineHeight + 4;

                if (boxY + boxHeight > doc.page.height - 80) {
                    doc.addPage();
                }

                doc
                    .rect(60, doc.y, doc.page.width - 120, boxHeight)
                    .fill(C.formulaBg);

                const innerY = doc.y + boxPad;
                doc
                    .fillColor(C.accent)
                    .fontSize(8)
                    .font('Helvetica-Bold')
                    .text('FORMULAS / RULES', 72, innerY, { characterSpacing: 0.8 });

                section.formulas.forEach((formula, i) => {
                    doc
                        .fillColor(C.body)
                        .fontSize(10)
                        .font('Courier')
                        .text(formula, 72, innerY + lineHeight + i * lineHeight, { lineGap: 2 });
                });

                doc.y = doc.y + boxHeight + 4;
                doc.moveDown(0.3);
            }

            // Section separator (skip after last)
            if (idx < notes.sections.length - 1) {
                doc.moveDown(0.6);
                doc
                    .moveTo(60, doc.y)
                    .lineTo(doc.page.width - 60, doc.y)
                    .strokeColor(C.rule)
                    .lineWidth(0.5)
                    .dash(3, { space: 4 })
                    .stroke()
                    .undash();
                doc.moveDown(0.8);
            }

            // Proactive page check before next section
            if (doc.y > doc.page.height - 120 && idx < notes.sections.length - 1) {
                doc.addPage();
            }
        });

        // ── Footer on each page ───────────────────────────────────────────
        const totalPages = doc.bufferedPageRange().count;
        for (let i = 0; i < totalPages; i++) {
            doc.switchToPage(i);
            doc
                .fillColor(C.muted)
                .fontSize(8)
                .font('Helvetica')
                .text(
                    `VectorOne AI  ·  Study Notes  ·  Page ${i + 1} of ${totalPages}`,
                    60,
                    doc.page.height - 36,
                    { align: 'center', width: doc.page.width - 120 }
                );
        }

        doc.end();
    } catch (err) {
        reportServerError(err, { route: 'GET /api/notes/:videoId/pdf' });
        if (!res.headersSent) {
            return res.status(500).json({ error: 'Failed to generate PDF' });
        }
    }
}
